"""Shared reader-facing clarity policy for lead writing and independent review."""

POLICY = (
    '导语压缩的是旁支，不是让陌生读者看懂并想读的关键信息。'
    '先从实际正文选择最有吸引力的一条行动链：谁因什么具体处境做了什么，'
    '产生或将产生什么值得看的变化。若人物身份或关系正是吸引点，姓名不能替代该信息；'
    '若事件的具体内容才产生冲击，不能只留差评、事故、秘密、下注等事件名称；'
    '若动作的收益、代价或对方回应改变预期，不能只写动作而删去它的作用。'
    '安排必要先后与因果，分句分段，不把多场事件硬塞进一个长句。'
    '收尾落到本篇具体行动、回应、原因或待兑现变化，不能只剩主题与愿望。'
    '仅凭导语复述上述行动链：若必须从标题、合同或后文补入关键事实才能说明吸引点，'
    '指出导语原句缺了什么、怎样损害理解或期待，据此修订；不能用信息密度高或简洁代替判断。'
    '只选择本篇有作用的信息，不要求每篇都有身份标签、数字、对白、危险或收益；'
    '不得补造正文没有的事实，也不要求把全篇过程讲完。'
)
